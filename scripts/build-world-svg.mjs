/**
 * Bakes a simplified flat-projection world map out of the Natural Earth
 * boundaries already in data/boundaries, so the aging-inventory page can render
 * a real coastline as inline SVG with no runtime dependency and no Mapbox call.
 *
 * Equirectangular, cropped to the inhabited latitudes (Antarctica dropped — it
 * has no distilleries and eats a third of the canvas).
 *
 * Run: node scripts/build-world-svg.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

const SRC = "data/boundaries/ne_10m_admin_0_countries.geojson";
const OUT = "src/lib/world-map-paths.ts";

// Canvas + crop. LAT_TOP/LAT_BOTTOM chop the empty poles.
const WIDTH = 2000;
const LAT_TOP = 84;
const LAT_BOTTOM = -56;
const SCALE = WIDTH / 360;
const HEIGHT = Math.round((LAT_TOP - LAT_BOTTOM) * SCALE);

// Countries drawn separately so the page can tint them by evidence tier.
const HIGHLIGHT = new Set([
  "USA", "CAN", "GBR", "IRL", "JPN", "IND", "TWN", "AUS", "ZAF",
]);

const project = ([lon, lat]) => [
  (lon + 180) * SCALE,
  (LAT_TOP - lat) * SCALE,
];

// Natural Earth 10m is far more detail than a 2000px silhouette can show, so we
// quantise to whole pixels AND drop points closer than MIN_STEP to the last one
// kept. Together these take the payload from ~1.4MB to something shippable.
const q = (n) => Math.round(n);
const MIN_STEP = 3;
const MIN_RING_AREA = 30;

function ringArea(pts) {
  let a = 0;
  for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
    a += pts[j][0] * pts[i][1] - pts[i][0] * pts[j][1];
  }
  return Math.abs(a / 2);
}

function ringToPath(ring) {
  const pts = [];
  for (const c of ring) {
    const [x, y] = project(c);
    const p = [q(x), q(y)];
    const last = pts[pts.length - 1];
    if (!last) {
      pts.push(p);
      continue;
    }
    const dx = p[0] - last[0];
    const dy = p[1] - last[1];
    if (dx * dx + dy * dy >= MIN_STEP * MIN_STEP) pts.push(p);
  }
  if (pts.length < 4) return null;
  // Drop specks — invisible at this canvas size, but they dominate the payload.
  if (ringArea(pts) < MIN_RING_AREA) return null;
  return `M${pts.map((p) => `${p[0]} ${p[1]}`).join("L")}Z`;
}

function featureToPath(geom) {
  const polys =
    geom.type === "Polygon" ? [geom.coordinates]
    : geom.type === "MultiPolygon" ? geom.coordinates
    : [];
  const parts = [];
  for (const poly of polys) {
    for (const ring of poly) {
      const p = ringToPath(ring);
      if (p) parts.push(p);
    }
  }
  return parts.join("");
}

const fc = JSON.parse(readFileSync(SRC, "utf8"));

const highlights = {};
const base = [];

for (const f of fc.features) {
  const p = f.properties ?? {};
  const iso = p.ADM0_A3 ?? p.ISO_A3;
  if (iso === "ATA") continue; // Antarctica — cropped out anyway
  const d = featureToPath(f.geometry);
  if (!d) continue;
  if (HIGHLIGHT.has(iso)) {
    highlights[iso] = (highlights[iso] ?? "") + d;
  } else {
    base.push(d);
  }
}

const out = `// GENERATED by scripts/build-world-svg.mjs — do not edit by hand.
// Source: Natural Earth 10m admin-0 (public domain), simplified to a half-pixel
// grid on a 2000px equirectangular canvas cropped to ${LAT_TOP}N–${Math.abs(LAT_BOTTOM)}S.

export const MAP_WIDTH = ${WIDTH};
export const MAP_HEIGHT = ${HEIGHT};
export const LAT_TOP = ${LAT_TOP};
export const LAT_BOTTOM = ${LAT_BOTTOM};

/** Project lon/lat into the baked SVG's coordinate space. */
export function project(lon: number, lat: number): [number, number] {
  return [(lon + 180) * ${SCALE}, (${LAT_TOP} - lat) * ${SCALE}];
}

/** Everything that isn't separately tinted. */
export const WORLD_BASE_PATH = ${JSON.stringify(base.join(""))};

/** Countries drawn on their own so the page can colour them by evidence tier. */
export const COUNTRY_PATHS: Record<string, string> = ${JSON.stringify(highlights, null, 0)};
`;

writeFileSync(OUT, out);
console.log(
  `wrote ${OUT} — ${(out.length / 1024).toFixed(0)}KB, ` +
  `${Object.keys(highlights).length} tinted countries, canvas ${WIDTH}x${HEIGHT}`
);
